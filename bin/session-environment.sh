#!/bin/bash

# Ensure target directory exists
mkdir -p "$HOME/.config/environment.d"
ENV_FILE="$HOME/.config/environment.d/session.conf"

# 1. SSH Dynamic Variables
export SSH_ASKPASS=$(command -v ssh-askpass || command -v ksshaskpass || command -v /usr/local/bin/ssh-askpass || command -v /opt/homebrew/bin/ssh-askpass || echo "")
export SSH_ASKPASS_REQUIRE="prefer"
export SSH_AUTH_SOCK="${XDG_RUNTIME_DIR}/ssh-agent.socket"

# 2. PATH & XDG Variables
export PATH="$HOME/.local/bin:$PATH"
export XDG_CONFIG_HOME="$HOME/.config"
export XDG_DATA_HOME="$HOME/.local/share"
export XDG_CACHE_HOME="$HOME/.cache"
export XDG_STATE_HOME="$HOME/.local/state"

# 3. Static Standard Variables
export EDITOR="emacsclient -t"
export VISUAL="emacsclient -c -a \"\""
export PAGER="less"
export MANPAGER="less"
export MANROFFOPT="-P -c"
export WORDCHARS="${WORDCHARS//[&.;]/}"
export SUDO_PROMPT=$'\e[38;2;207;34;46mPassword:\e[0m '
export DIFFPROG="emacs -nw"

# 4. UI/Less Variables
export LESS_MINT=$'\e[38;5;50m'
export LESS_BLUE=$'\e[38;5;28m'
export LESS_RESET=$'\e[0m'
export LESS="-S -R -F --incsearch --mouse --use-color -Dd33.16 -Du33.16 -Ds43.16 -DP43.16 -DR33.16 -DE43.16 -DS43.16"
export LESS_TERMCAP_md="${LESS_MINT}"
export LESS_TERMCAP_me="${LESS_RESET}"
export LESS_TERMCAP_us="${LESS_BLUE}"
export LESS_TERMCAP_ue="${LESS_RESET}"
export LESS_TERMCAP_so=$'\e[48;5;43;30m'
export LESS_TERMCAP_se="${LESS_RESET}"

# 5. KDE Color Engine
# KDE stores wallpaper info in plasma-org.kde.plasma.desktop-appletsrc
# We use grep/sed to find the first occurrence of an image path
WALLPAPER_PATH=$(grep -m 1 "image=" "$HOME/.config/plasma-org.kde.plasma.desktop-appletsrc" 2>/dev/null | sed 's/.*image=\([^"]*\).*/\1/')

# 6. Color Extraction (using ImageMagick)
if [[ -n "$WALLPAPER_PATH" && -f "$WALLPAPER_PATH" ]]; then
    # Get the average color in HEX format
    THEME_COLOR_PRIMARY=$(magick "$WALLPAPER_PATH" -scale 1x1! -format "%[hex]" info: | sed 's/^/#/')
else
    # Fallback color if wallpaper not found or invalid
    THEME_COLOR_PRIMARY="#1e1e2e"
fi
export THEME_COLOR_PRIMARY
export WALLPAPER_PATH


# 7. Write to Single Source of Truth (systemd environment.d format)
# We write to ~/.config/environment.d/session.conf so it's picked up by systemd automatically
# Using %q ensures values are properly quoted for systemd parsing
{
    echo "# Generated by session-environment.sh"
    printf "SSH_ASKPASS=%q\n" "$SSH_ASKPASS"
    printf "SSH_ASKPASS_REQUIRE=%q\n" "$SSH_ASKPASS_REQUIRE"
    printf "SSH_AUTH_SOCK=%q\n" "$SSH_AUTH_SOCK"
    printf "PATH=%q\n" "$PATH"
    printf "XDG_CONFIG_HOME=%q\n" "$XDG_CONFIG_HOME"
    printf "XDG_DATA_HOME=%q\n" "$XDG_DATA_HOME"
    printf "XDG_CACHE_HOME=%q\n" "$XDG_CACHE_HOME"
    printf "XDG_STATE_HOME=%q\n" "$XDG_STATE_HOME"
    printf "EDITOR=%q\n" "$EDITOR"
    printf "VISUAL=%q\n" "$VISUAL"
    printf "PAGER=%q\n" "$PAGER"
    printf "MANPAGER=%q\n" "$MANPAGER"
    printf "MANROFFOPT=%q\n" "$MANROFFOPT"
    printf "WORDCHARS=%q\n" "$WORDCHARS"
    printf "SUDO_PROMPT=%q\n" "$SUDO_PROMPT"
    printf "DIFFPROG=%q\n" "$DIFFPROG"
    printf "LESS=%q\n" "$LESS"
    printf "LESS_MINT=%q\n" "$LESS_MINT"
    printf "LESS_BLUE=%q\n" "$LESS_BLUE"
    printf "LESS_RESET=%q\n" "$LESS_RESET"
    printf "LESS_TERMCAP_md=%q\n" "$LESS_TERMCAP_md"
    printf "LESS_TERMCAP_me=%q\n" "$LESS_TERMCAP_me"
    printf "LESS_TERMCAP_us=%q\n" "$LESS_TERMCAP_us"
    printf "LESS_TERMCAP_ue=%q\n" "$LESS_TERMCAP_ue"
    printf "LESS_TERMCAP_so=%q\n" "$LESS_TERMCAP_so"
    printf "LESS_TERMCAP_se=%q\n" "$LESS_TERMCAP_se"
    printf "THEME_COLOR_PRIMARY=%q\n" "$THEME_COLOR_PRIMARY"
    printf "WALLPAPER_PATH=%q\n" "$WALLPAPER_PATH"
} > "$ENV_FILE"

# 8. Broadcast to current systemd session
systemctl --user import-environment \
    SSH_ASKPASS SSH_ASKPASS_REQUIRE SSH_AUTH_SOCK \
    PATH XDG_CONFIG_HOME XDG_DATA_HOME XDG_CACHE_HOME XDG_STATE_HOME \
    EDITOR VISUAL PAGER MANPAGER MANROFFOPT WORDCHARS SUDO_PROMPT DIFFPROG \
    LESS LESS_MINT LESS_BLUE LESS_RESET \
    LESS_TERMCAP_md LESS_TERMCAP_me LESS_TERMCAP_us LESS_TERMCAP_ue \
    LESS_TERMCAP_so LESS_TERMCAP_se \
    THEME_COLOR_PRIMARY WALLPAPER_PATH 
